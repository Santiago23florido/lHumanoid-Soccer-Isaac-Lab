def _uniform(bounds, size, generator, device) -> torch.Tensor:
    low, high = bounds
    return low + (high - low) * torch.rand(size, generator=generator, device=device)


def feasible(
    period: torch.Tensor,
    duty: torch.Tensor,
    forward: torch.Tensor,
    lateral: torch.Tensor,
    width: torch.Tensor,
    ranges: GaitRanges,
    min_swing: float,
) -> torch.Tensor:
    """Which gaits a leg can carry out: long enough swings, strides within reach, bounded bounce."""
    speed = torch.hypot(forward, lateral)
    ok = ((1.0 - duty) * period[:, None] >= min_swing).all(dim=-1)
    ok &= speed * period <= ranges.max_stride
    half = period / 2
    step = torch.maximum(
        torch.hypot(forward * half, lateral * half + width),
        torch.hypot(forward * half, lateral * half - width),
    )
    ok &= step <= ranges.max_step
    ok &= (speed[:, None] / (1.0 - duty)).amax(dim=-1) <= ranges.max_swing_speed
    peak = torch.pi / (4.0 * duty)
    bounce = (peak - 1.0).clamp(min=0.0) * (duty * period[:, None] / torch.pi) ** 2
    ok &= bounce.amax(dim=-1) <= ranges.max_bounce
    return ok


def sample_parameters(
    n: int,
    ranges: GaitRanges,
    min_swing: float,
    generator: torch.Generator,
    device: torch.device | str,
) -> dict[str, torch.Tensor]:
    """``n`` segments of gait, uniform over the feasible part of the ranges."""
    pieces: dict[str, list[torch.Tensor]] = {}
    have = 0
    while have < n:
        m = max(2 * (n - have), 256)
        low, high = ranges.period
        period = torch.exp(_uniform((math.log(low), math.log(high)), m, generator, device))
        mean = _uniform(ranges.duty, m, generator, device)
        asymmetry = _uniform((-ranges.duty_asymmetry, ranges.duty_asymmetry), m, generator, device)
        duty = torch.stack([mean + asymmetry / 2, mean - asymmetry / 2], dim=-1).clamp(0.05, 0.98)
        draw = {
            "forward": _uniform(ranges.forward, m, generator, device),
            "lateral": _uniform(ranges.lateral, m, generator, device),
            "turn": _uniform(ranges.turn, m, generator, device),
            "period": period,
            "duty": duty,
            "width": _uniform(ranges.width, m, generator, device),
            "height": _uniform(ranges.height, m, generator, device),
            "clearance": _uniform(ranges.clearance, m, generator, device),
            "lean": _uniform(ranges.lean, m, generator, device),
        }
        ok = feasible(
            period, duty, draw["forward"], draw["lateral"], draw["width"], ranges, min_swing
        )
        for key, value in draw.items():
            pieces.setdefault(key, []).append(value[ok])
        have += int(ok.sum())
    params = {key: torch.cat(value)[:n] for key, value in pieces.items()}
    params["standing"] = torch.rand(n, generator=generator, device=device) < ranges.standing
    params["first"] = (torch.rand(n, generator=generator, device=device) < 0.5).long()
    params["duration"] = _uniform(ranges.segment, n, generator, device)
    return params


def standing_skill(n: int, device: torch.device | str = "cpu") -> torch.Tensor:
    """A canonical upright stance, ``(n, 27)``: what an environment holds before it is anchored."""
    z = torch.zeros(n, SKILL, device=device)
    z[:, _HEIGHT] = 0.94
    z[:, _GRAVITY.start + 2] = -1.0
    feet = torch.tensor([[0.0, 0.2, -0.94], [0.0, -0.2, -0.94]], device=device)
    z[:, _FEET] = feet.flatten()
    z[:, _LOAD] = 0.5
    return z


def _rotate(
    angle: torch.Tensor, x: torch.Tensor, y: torch.Tensor
) -> tuple[torch.Tensor, torch.Tensor]:
    c, s = torch.cos(angle), torch.sin(angle)
    return c * x - s * y, s * x + c * y


def _expand(mask: torch.Tensor, like: torch.Tensor) -> torch.Tensor:
    return mask.view(-1, *([1] * (like.dim() - 1)))


class PointMassBiped:
    """The family's generator: one biped per environment, run ahead of the body.

    Every step is the same sequence of tensor operations for every
    environment, whatever mode it is in, so the GPU never waits on a branch:
    a mode change, a landing or a new segment is a mask, not an ``if``. On a
    GPU the step is captured once as a CUDA graph and replayed: a thousand
    small kernels cost one launch (45 ms a step for 4096 bipeds before, a few
    after). The state lives in tensors that never move, and the step writes
    back into them.

    Args:
        num_envs: Environments; each has its own biped, schedule and episode.
        ranges: The family.
        body_step: The body's control step, in ``T``. A swing must last
            :data:`SWING_STEPS` of them to be seen on that body (the G1 walk
            teacher's shortest swings last 1.9), so the shortest swing is
            ``max(ranges.min_swing, SWING_STEPS body_step)`` -- the only place a
            body enters the family.
        substep: The biped's integration step, in ``T``.
        horizon: How far past now a plan reaches, in ``T``.
        seed: Seeds the biped's own generator; nothing else is random.
        graph: Capture the step as a CUDA graph on a GPU (off: step eagerly, for checks).
    """

    def __init__(
        self,
        num_envs: int,
        ranges: GaitRanges | None = None,
        *,
        body_step: float,
        substep: float,
        horizon: float,
        device: torch.device | str = "cpu",
        seed: int = 0,
        graph: bool = True,
    ) -> None:
        self.num_envs = n = num_envs
        self.use_graph = graph
        self.ranges = ranges = ranges or GaitRanges()
        self.device = torch.device(device)
        self.body_step = float(body_step)
        self.substep = float(substep)
        self.horizon = float(horizon)
        self.min_swing = max(ranges.min_swing, SWING_STEPS * self.body_step)
        self.generator = torch.Generator(device=self.device)
        self.generator.manual_seed(seed)

        ahead = self.horizon / self.substep
        self.slots = int(math.ceil(ahead + self.body_step / self.substep)) + 4
        self.buffer = torch.zeros(n, self.slots, SKILL + _EXTRA, device=self.device)
        self.now = 0.0
        """Now, in substeps since the biped started: where the bodies are."""
        self.end = int(math.floor(ahead)) + 2
        """The last substep written: the bipeds run this far ahead."""
        self.substeps = 0
        self.offsets: torch.Tensor | None = None
        self.graph: torch.cuda.CUDAGraph | None = None
        self.side = torch.tensor([1.0, -1.0], device=self.device)

        def zeros(*shape: int, dtype: torch.dtype = torch.float32) -> torch.Tensor:
            return torch.zeros(n, *shape, device=self.device, dtype=dtype)

        def full(value: float, *shape: int) -> torch.Tensor:
            return torch.full((n, *shape), value, device=self.device)

        self.com, self.vel = zeros(3), zeros(3)
        self.yaw, self.yaw_rate = zeros(), zeros()
        self.lean, self.lean_rate = zeros(), zeros()
        self.foot, self.foot_vel = zeros(2, 3), zeros(2, 3)
        self.contact = torch.ones(n, 2, dtype=torch.bool, device=self.device)
        self.liftoff = zeros(2, 3)
        self.target, self.target_rate = zeros(2, 2), zeros(2, 2)
        self.swing_time, self.stance_time = zeros(2), zeros(2)
        self.load, self.cop = zeros(2), zeros(2)
        self.amplitude = full(math.pi / (4.0 * START_DUTY), 2)
        """Peak of each foot's half-sine of load for its current stance, in ``m g``."""
        self.phase = zeros()
        self.offset = full(0.5)
        self.mode = zeros(dtype=torch.long)
        self.mode_time = zeros()
        self.shift_time = full(SHIFT_TIME)
        self.recovering = zeros(dtype=torch.bool)
        """Envs stepping in place to get back to a gait their schedule can continue."""
        self.recoveries = zeros(dtype=torch.long)
        """How many times each env has had to recover, for diagnostics."""
        self.fallen = zeros(dtype=torch.bool)
        """Envs whose biped fell all the same: their plan holds still until the next anchor."""
        self.frozen = zeros(SKILL + _EXTRA)
        self.blend_time = full(BLEND_TIME)
        self.blend_from = zeros(2)
        self.first = zeros(dtype=torch.long)
        self.xi_start, self.xi_end = zeros(2), zeros(2)
        self.xi_ref = zeros(2)
        """The DCM of the periodic gait, from the last landing on: what the CoP tracks."""
        self.landing_xi = zeros(2, 2)
        """The DCM each swinging foot was placed for at its landing (:meth:`_aim`)."""
        self.period = full(1.0)
        self.duty = full(START_DUTY, 2)
        self.width = full(0.4)
        self.clearance = full(0.05, 2)
        self.height = full(0.94)
        self.z_avg, self.zd_avg, self.z_int = full(0.94), zeros(), zeros()
        self.v_cmd, self.w_cmd = zeros(2), zeros()
        self.v_noise, self.w_noise = zeros(2), zeros()
        self.v_int, self.v_avg = zeros(2), zeros(2)
        self.leg_orbit, self.yaw_inertia = zeros(), zeros()
        self.draw_v, self.draw_w = zeros(2), zeros()
        """Standard normal draws for the intent's wander, made outside the step."""
        self.record = zeros(SKILL + _EXTRA)
        """The step's output: ``z*`` now, then the CoM ``x, y`` and yaw (:meth:`_record`)."""
        self.fixed = zeros(dtype=torch.bool)
        self.probe: dict[str, torch.Tensor] = {}
        self.bank = sample_parameters(BANK, ranges, self.min_swing, self.generator, self.device)
        self.goal = self._draw(n)
        self.next = self._draw(n)
        self.spare = self._draw(n)
        self.segment_left = full(math.inf)
        self.anchor(torch.arange(n, device=self.device), standing_skill(n, self.device))

    # -- the interface ---------------------------------------------------------

    def set_probes(self, ids: torch.Tensor, params: dict[str, torch.Tensor]) -> None:
        """Hold ``ids`` to one gait each (``GAIT_KEYS`` plus an optional ``offset``) from their
        next anchor on: evaluation, where a tracker is scored gait by gait."""
        ids = ids.to(self.device)
        self.fixed[ids] = True
        if not self.probe:
            self.probe = {key: self.next[key].clone() for key in GAIT_KEYS}
            self.probe["offset"] = self.offset.clone()
        for key, value in params.items():
            self.probe[key][ids] = value.to(self.device, self.probe[key].dtype)
        self.probe["standing"][ids] = False

    def set_offsets(self, offsets: torch.Tensor) -> None:
        """The body times after now at which :meth:`plan` reads the trajectory, ``(L,)``."""
        offsets = torch.as_tensor(offsets, dtype=torch.float64).cpu()
        if float(offsets.max()) > self.horizon + 1e-9 or float(offsets.min()) < 0.0:
            raise ValueError(f"plan offsets must lie within [0, {self.horizon}] body times")
        self.offsets = (offsets / self.substep).to(self.device)

    def anchor(self, ids: torch.Tensor, skill: torch.Tensor) -> None:
        """Start a new episode for ``ids`` from a body's ``z*`` (body units, ``(k, 27)``).

        The biped takes the body's height, tilt and feet, and holds them still
        for as long as a plan reaches, then stands for ``first_stand`` and
        starts a gait. Its world is the body's heading frame at this instant,
        centred on the body's CoM.
        """
        ids = ids.to(self.device)
        k = len(ids)
        if k == 0:
            return
        skill = skill.to(self.device, torch.float32)
        r = self.ranges
        height = skill[:, _HEIGHT].clamp(0.5, 1.2)
        rel = skill[:, _FEET].reshape(k, 2, 3)
        com = torch.zeros(k, 3, device=self.device)
        com[:, 2] = height
        feet = com[:, None, :] + rel
        feet[..., 2] = 0.0

        self.com[ids], self.vel[ids] = com, 0.0
        self.yaw[ids], self.yaw_rate[ids] = 0.0, 0.0
        self.lean[ids] = torch.asin(skill[:, _GRAVITY.start].clamp(-0.5, 0.5))
        self.lean_rate[ids] = 0.0
        self.foot[ids], self.foot_vel[ids] = feet, 0.0
        self.contact[ids] = True
        self.liftoff[ids], self.target[ids], self.target_rate[ids] = feet, feet[..., :2], 0.0
        self.swing_time[ids], self.stance_time[ids] = 0.0, 0.0
        self.phase[ids] = 0.0
        self.mode[ids], self.mode_time[ids] = STAND, 0.0
        self.shift_time[ids], self.recovering[ids], self.fallen[ids] = SHIFT_TIME, False, False
        self.blend_time[ids] = BLEND_TIME
        self.duty[ids] = START_DUTY
        self.amplitude[ids] = math.pi / (4.0 * START_DUTY)
        self.height[ids], self.z_avg[ids], self.zd_avg[ids] = height, height, 0.0
        self.z_int[ids] = 0.0
        for name in ("v_cmd", "w_cmd", "v_noise", "w_noise", "v_int", "v_avg"):
            getattr(self, name)[ids] = 0.0
        # Hold the centre of mass where the body has it.
        self.xi_start[ids], self.xi_end[ids], self.xi_ref[ids] = 0.0, 0.0, 0.0
        self.landing_xi[ids] = 0.0

        g, dev = self.generator, self.device
        offset = 0.5 + _uniform((-r.phase_jitter, r.phase_jitter), k, g, dev)
        self.leg_orbit[ids] = _uniform(r.leg_orbit, k, g, dev)
        self.yaw_inertia[ids] = _uniform(r.yaw_inertia, k, g, dev)
        first = self._draw(k)
        first["standing"][:] = True
        first["duration"] = _uniform(r.first_stand, k, g, dev)
        then = self._draw(k)
        then["standing"][:] = False
        if self.probe:
            fixed = self.fixed[ids]
            for key in GAIT_KEYS:
                then[key] = torch.where(_expand(fixed, then[key]), self.probe[key][ids], then[key])
            offset = torch.where(fixed, self.probe["offset"][ids], offset)
        self.offset[ids] = offset
        for key in GAIT_KEYS:
            self.goal[key][ids] = first[key]
            self.next[key][ids] = then[key]
        self.segment_left[ids] = first["duration"]
        self.period[ids] = then["period"]
        self.width[ids] = then["width"]

        load, cop, _ = self._balance()
        self.load[ids], self.cop[ids] = load[ids], cop[ids]
        record = self._record()[ids]
        self.record[ids] = record
        span = torch.arange(int(math.floor(self.now)), self.end + 1, device=self.device)
        self.buffer[ids[:, None], (span % self.slots)[None, :]] = record[:, None, :]

    def advance(self) -> None:
        """Move now on by one body step, and the bipeds on to cover a plan from there."""
        self.now += self.body_step / self.substep
        needed = int(math.floor(self.now + self.horizon / self.substep)) + 2
        while self.end < needed:
            self.substeps += 1
            if self.substeps % SPARE_EVERY == 0:
                for key, value in self._draw(self.num_envs).items():
                    self.spare[key].copy_(value)
            self.draw_v.normal_(generator=self.generator)
            self.draw_w.normal_(generator=self.generator)
            if self.device.type == "cuda" and self.use_graph:
                if self.graph is None:
                    self._capture()
                self.graph.replay()
            else:
                self._step(self.substep)
            self.end += 1
            self.buffer[:, self.end % self.slots] = self.record

    def _capture(self) -> None:
        """Record one step as a CUDA graph, on a copy of the state, then put the state back."""
        saved = {name: getattr(self, name).clone() for name in _STATE}
        saved_goal = {key: value.clone() for key, value in self.goal.items()}
        saved_next = {key: value.clone() for key, value in self.next.items()}
        stream = torch.cuda.Stream(device=self.device)
        stream.wait_stream(torch.cuda.current_stream(self.device))
        with torch.cuda.stream(stream):
            for _ in range(3):
                self._step(self.substep)
        torch.cuda.current_stream(self.device).wait_stream(stream)
        self.graph = torch.cuda.CUDAGraph()
        with torch.cuda.graph(self.graph):
            self._step(self.substep)
        for name, value in saved.items():
            getattr(self, name).copy_(value)
        for key, value in saved_goal.items():
            self.goal[key].copy_(value)
        for key, value in saved_next.items():
            self.next[key].copy_(value)

    def plan(self, ids: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """The trajectory ahead of ``ids``, read at the offsets of :meth:`set_offsets`.

        Returns ``z*`` ``(k, L, 27)`` in body units; the integrals ``(k, L, 3)``
        -- the CoM's displacement in leg lengths in the heading frame of now,
        and the turn -- exactly, not integrated from velocities; and ``z*`` now,
        ``(k, 27)``.
        """
        if self.offsets is None:
            raise RuntimeError("set_offsets() first")
        ids = ids.to(self.device)
        rows = self.buffer[ids]
        positions = self.now + self.offsets
        base = torch.floor(positions)
        weight = (positions - base).to(torch.float32)[None, :, None]
        low = base.long() % self.slots
        ahead = rows[:, low] + (rows[:, (low + 1) % self.slots] - rows[:, low]) * weight
        whole = int(math.floor(self.now))
        part = self.now - whole
        here = rows[:, whole % self.slots]
        here = here + (rows[:, (whole + 1) % self.slots] - here) * part
        moved_x = ahead[..., SKILL] - here[:, None, SKILL]
        moved_y = ahead[..., SKILL + 1] - here[:, None, SKILL + 1]
        yaw = here[:, SKILL + 2]
        dx, dy = _rotate(-yaw[:, None], moved_x, moved_y)
        turned = ahead[..., SKILL + 2] - yaw[:, None]
        return ahead[..., :SKILL], torch.stack([dx, dy, turned], dim=-1), here[:, :SKILL]

    # -- the biped ---------------------------------------------------------------

    def _draw(self, n: int) -> dict[str, torch.Tensor]:
        """``n`` segments from the bank of feasible ones; standing, first foot and length fresh."""
        g, dev, r = self.generator, self.device, self.ranges
        index = torch.randint(0, BANK, (n,), generator=g, device=dev)
        params = {key: self.bank[key][index] for key in _GAIT_SHAPE}
        params["standing"] = torch.rand(n, generator=g, device=dev) < r.standing
        params["first"] = (torch.rand(n, generator=g, device=dev) < 0.5).long()
        params["duration"] = _uniform(r.segment, n, g, dev)
        return params

    def _frac(self) -> torch.Tensor:
        """``(n, 2)``: how far through its own cycle each foot is (0 at touchdown)."""
        return torch.stack([self.phase, torch.remainder(self.phase - self.offset, 1.0)], dim=-1)

    def _omega(self) -> torch.Tensor:
        return torch.rsqrt(self.z_avg.clamp(min=0.3))

    def _xi(self) -> torch.Tensor:
        return self.com[:, :2] + self.vel[:, :2] / self._omega()[:, None]

    def _heading(self) -> torch.Tensor:
        return torch.stack([torch.cos(self.yaw), torch.sin(self.yaw)], dim=-1)

    def _support(self, desired: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        """Share on the right foot and fore-aft offset that bring the CoP nearest ``desired``.

        The support is the segment between the two sole points, widened fore and
        aft by :data:`FOOT_HALF_LENGTH` along the heading: the CoP is ``a + λ (b −
        a) + m h`` with ``λ`` in [0, 1] (the right foot's share of the load) and
        ``|m|`` at most the half foot.
        """
        a, b = self.foot[:, 0, :2], self.foot[:, 1, :2]
        u = b - a
        hx = self._heading()
        d = desired - a
        det = u[:, 0] * hx[:, 1] - u[:, 1] * hx[:, 0]
        safe = det.abs() > 1e-4
        det = torch.where(safe, det, torch.ones_like(det))
        share = torch.where(
            safe,
            (d[:, 0] * hx[:, 1] - d[:, 1] * hx[:, 0]) / det,
            (d * u).sum(-1) / (u * u).sum(-1).clamp(min=1e-6),
        )
        fore = torch.where(safe, (u[:, 0] * d[:, 1] - u[:, 1] * d[:, 0]) / det, 0.0)
        return share.clamp(0.0, 1.0), fore.clamp(-FOOT_HALF_LENGTH, FOOT_HALF_LENGTH)

    def _held(self, desired: torch.Tensor) -> torch.Tensor:
        """The point of the support nearest ``desired``."""
        share, fore = self._support(desired)
        a, b = self.foot[:, 0, :2], self.foot[:, 1, :2]
        return a + share[:, None] * (b - a) + fore[:, None] * self._heading()

    def _balance(self) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """Loads and CoP of a body holding (or moving) its DCM on both feet; the height factor."""
        kappa = HEIGHT_GAIN[0] * (self.height - self.z_avg) - HEIGHT_GAIN[1] * self.zd_avg
        kappa = (kappa + self.z_int).clamp(-0.5, 0.5)
        omega = self._omega()[:, None]
        xi = self.com[:, :2] + self.vel[:, :2] / omega
        shifting = (self.mode == SHIFT)[:, None]
        tau = (self.mode_time / self.shift_time).clamp(0.0, 1.0)[:, None]
        smooth = tau * tau * (3.0 - 2.0 * tau)
        rate = 6.0 * tau * (1.0 - tau) / self.shift_time[:, None]
        span = self.xi_end - self.xi_start
        reference = torch.where(shifting, self.xi_start + span * smooth, self.xi_end)
        reference_rate = torch.where(shifting, span * rate, torch.zeros_like(span))
        desired = xi + BALANCE_GAIN * (xi - reference) - reference_rate / omega
        share, fore = self._support(desired)
        # The end of a shift: the weight leaves the foot about to lift.
        settle = torch.minimum(torch.full_like(self.shift_time, SETTLE), self.shift_time / 2)
        late = ((self.mode_time - (self.shift_time - settle)) / settle).clamp(0.0, 1.0)
        late = late * (self.mode == SHIFT)
        stance_right = (1 - self.first).float()
        share = share * (1.0 - late) + stance_right * late
        fore = fore * (1.0 - late)
        force = 1.0 + kappa
        load = torch.stack([(1.0 - share) * force, share * force], dim=-1)
        a, b = self.foot[:, 0, :2], self.foot[:, 1, :2]
        cop = a + share[:, None] * (b - a) + fore[:, None] * self._heading()
        return load, cop, kappa

    @staticmethod
    def _trailing_share(
        span: torch.Tensor,
        trail_elapsed: torch.Tensor,
        trail_stance: torch.Tensor,
        lead_stance: torch.Tensor,
        omega: torch.Tensor,
    ) -> torch.Tensor:
        """``I = ω ∫_0^span e^{ω (span − t)} λ(t) dt``, ``λ`` the trailing foot's share of the load.

        A step from one landing to the next; the trailing foot has been down for
        ``trail_elapsed`` of a stance of ``trail_stance``, the leading one has just
        landed for ``lead_stance``. Their loads are the half-sines of the model, so
        ``λ`` is the share of the centre of pressure still on the trailing foot.
        """
        nodes = (torch.arange(_QUADRATURE, device=span.device) + 0.5) / _QUADRATURE
        t = span[..., None] * nodes
        trail_s = (trail_elapsed[..., None] + t) / trail_stance[..., None]
        lead_s = t / lead_stance[..., None]
        trail = torch.where(trail_s < 1.0, torch.sin(torch.pi * trail_s.clamp(0, 1)), 0.0)
        trail = trail / trail_stance[..., None]
        lead = torch.where(lead_s < 1.0, torch.sin(torch.pi * lead_s.clamp(0, 1)), 0.0)
        lead = lead / lead_stance[..., None]
        total = trail + lead
        share = torch.where(total > 1e-6, trail / total.clamp(min=1e-6), 0.5)
        weight = torch.exp(omega[..., None] * (span[..., None] - t))
        return omega * (weight * share).mean(dim=-1) * span

    @classmethod
    def _steady_offset(
        cls,
        side: torch.Tensor,
        width: torch.Tensor,
        velocity: torch.Tensor,
        before: torch.Tensor,
        after: torch.Tensor,
        yaw: torch.Tensor,
        omega: torch.Tensor,
        stance: torch.Tensor,
        other_stance: torch.Tensor,
        turn: torch.Tensor | float = 0.0,
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """Where the DCM sits relative to a foot just landed, for the gait to repeat.

        The foot ``k`` lands; the other foot ``j`` landed ``before`` earlier and
        lands again ``after`` later, and the two steps are ``l_in`` (onto ``k``) and
        ``l_out`` (onto ``j``). Over a step the linear pendulum's DCM follows
        ``ξ̇ = ω (ξ − p)``, and ``p`` slides from the trailing foot to the leading
        one as their loads cross. Integrating over both steps of the cycle and
        asking for the same offset at every landing of ``k``:

            a = [l_in (1 − E_2 I_1) + l_out (E_2 − I_2)] / (E_1 E_2 − 1),

        ``E = e^{ω t}`` for the step after ``k`` lands (1) and after ``j`` lands
        (2), ``I`` the trailing foot's weighted share over each
        (:meth:`_trailing_share`). With no double support ``I = 0``: forward
        ``l / (E − 1)``, sideways ``−w / (E + 1)``. With a long one the trailing
        foot drives the DCM on during the step, so it must land nearer to it --
        the deadbeat step of the linear pendulum, for the model's own centre of
        pressure.

        Turning at ``turn`` (``1/T``), the heading moves by ``Δ_1 = turn · after``
        and ``Δ_2 = turn · before`` over the two steps, each step points along its
        mid-heading, and the orbit is periodic in the heading frame, ``ã``:

            [R(Δ_1 + Δ_2) − E_1 E_2] ã = (E_2 I_1 R(−Δ_2/2) − R(Δ_1 + Δ_2/2)) l_in
                                        + (I_2 − E_2) R(Δ_1/2) l_out,

        which is the straight case's formula when ``Δ = 0``. Taken as straight, a
        sharp turn on a long double support fell over.

        All arguments broadcast; ``velocity`` is ``(..., 2)`` in the heading frame,
        ``stance`` and ``other_stance`` the two feet's stance times.

        Returns the offset ``(..., 2)``, and ``I_1`` and ``E_1``, which
        :meth:`_aim` needs to place the foot.
        """
        vx, vy = velocity[..., 0], velocity[..., 1]
        in_x, in_y = vx * before, vy * before + side * width
        out_x, out_y = vx * after, vy * after - side * width
        before, after = torch.broadcast_tensors(before, after)
        stance, other_stance = torch.broadcast_tensors(stance, other_stance)
        omega_b = torch.broadcast_to(omega, before.shape)
        first = cls._trailing_share(after, before, other_stance, stance, omega_b)
        second = cls._trailing_share(before, after, stance, other_stance, omega_b)
        e_first, e_second = torch.exp(omega_b * after), torch.exp(omega_b * before)
        turn_first, turn_second = turn * after, turn * before
        # The right-hand side, in the heading frame of the landing.
        a_x, a_y = _rotate(-turn_second / 2, in_x, in_y)
        b_x, b_y = _rotate(turn_first + turn_second / 2, in_x, in_y)
        c_x, c_y = _rotate(turn_first / 2, out_x, out_y)
        keep = e_second * first
        rhs_x = keep * a_x - b_x + (second - e_second) * c_x
        rhs_y = keep * a_y - b_y + (second - e_second) * c_y
        # [R(θ) − c] ã = rhs, with θ the cycle's turn and c = E_1 E_2.
        theta = turn_first + turn_second
        cos, sin = torch.cos(theta), torch.sin(theta)
        diagonal = cos - e_first * e_second
        det = (diagonal * diagonal + sin * sin).clamp(min=1e-6)
        local_x = (diagonal * rhs_x + sin * rhs_y) / det
        local_y = (-sin * rhs_x + diagonal * rhs_y) / det
        world_x, world_y = _rotate(yaw, local_x, local_y)
        return torch.stack([world_x, world_y], dim=-1), first, e_first

    def _aim(self, frac: torch.Tensor, until_landing: torch.Tensor, velocity: torch.Tensor):
        """``(n, 2, 2)``: where each foot should land, from the state predicted at its landing."""
        duty_mean = self.duty.mean(dim=-1)
        stiffness = torch.clamp(1.0 / (2.0 * duty_mean), min=1.0)
        omega = (self._omega() * torch.sqrt(stiffness))[:, None]
        other = self.foot[..., :2].flip(1)
        other_contact = self.contact.flip(1)
        other_frac = frac.flip(1)
        other_duty = self.duty.flip(1)
        other_lift = torch.remainder(other_duty - other_frac, 1.0) * self.period[:, None]
        stance = torch.where(other_contact, torch.minimum(other_lift, until_landing), 0.0)
        flight = until_landing - stance
        ch, sh = torch.cosh(omega * stance), torch.sinh(omega * stance)
        c0, v0 = self.com[:, None, :2], self.vel[:, None, :2]
        com = other + (c0 - other) * ch[..., None] + v0 / omega[..., None] * sh[..., None]
        vel = (c0 - other) * (omega * sh)[..., None] + v0 * ch[..., None]
        com = com + vel * flight[..., None]
        xi = com + vel / omega[..., None]
        yaw = self.yaw[:, None] + self.yaw_rate[:, None] * until_landing
        side = self.side
        period = self.period[:, None]
        offset = self.offset[:, None]
        before = torch.cat([(1.0 - offset), offset], dim=-1) * period
        after = torch.cat([offset, (1.0 - offset)], dim=-1) * period
        width = self.width[:, None]
        stance_next = (self.goal["duty"] * period).clamp(min=0.05)
        other_stance = (other_duty * period).clamp(min=0.05)
        turn = self.yaw_rate[:, None]
        offset_k, share, growth = self._steady_offset(
            side,
            width,
            velocity[:, None, :],
            before,
            after,
            yaw,
            omega,
            stance_next,
            other_stance,
            turn,
        )
        # Place the foot so that, after the step it starts, the DCM is on the gait's
        # orbit at the other foot's next landing -- with the CoP sliding off the
        # trailing foot where it really is: E_1 ξ − I_1 r_j − (E_1 − I_1) r_k = a_j + l_out.
        # On the orbit this is ξ − a_k; off it, the error is gone after one step.
        # Taking the trailing foot as nominal instead (ξ − a_k) leaves an error that
        # grows by about I_1 each step: long double supports fell sideways.
        out_x, out_y = _rotate(
            yaw + turn * after / 2,
            velocity[:, None, 0] * after,
            velocity[:, None, 1] * after - side * width,
        )
        leaving = torch.stack([out_x, out_y], dim=-1)
        walk = growth[..., None] * xi - share[..., None] * other - offset_k.flip(1) - leaving
        walk = walk / (growth - share).clamp(min=1.0)[..., None]
        # Runs: the neutral point, half the coming stance ahead, and a velocity gain.
        target_vx, target_vy = _rotate(yaw, velocity[:, None, 0], velocity[:, None, 1])
        target_vel = torch.stack([target_vx, target_vy], dim=-1)
        lateral_x, lateral_y = _rotate(yaw, torch.zeros_like(yaw), side * self.width[:, None] / 2)
        run = (
            com
            + vel * (stance_next / 2)[..., None]
            + RAIBERT_GAIN * (vel - target_vel)
            + torch.stack([lateral_x, lateral_y], dim=-1)
        )
        running = (duty_mean < 0.5)[:, None, None]
        target = torch.where(running, run, walk)
        # Never across the other foot, never beyond reach.
        partner = torch.where(other_contact[..., None], other, self.target.flip(1))
        normal = torch.stack([-torch.sin(yaw), torch.cos(yaw)], dim=-1)
        apart = side * ((target - partner) * normal).sum(-1)
        target = target + (side * (MIN_SEPARATION - apart).clamp(min=0.0))[..., None] * normal
        reach = target - com
        distance = reach.norm(dim=-1, keepdim=True)
        return com + reach * (REACH / distance.clamp(min=REACH)), xi

    def _track(
        self, nominal: torch.Tensor, gait: torch.Tensor, dt: float
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Loads and an ankle offset of the CoP that steer the DCM back to the periodic gait's.

        The nominal half-sines move the CoP along the feet as the plan was laid
        out; ``ξ_ref`` integrates the linear pendulum under that CoP from each
        landing's planned offset. The CoP is then led by ``COP_GAIN (ξ - ξ_ref)``:
        first within each loaded sole, then, in double support, by moving load
        between the feet -- by at most :data:`SHARE_LIMIT`, fading as either foot
        lands or lifts, so no load jumps. Runs, which spend time in the air, keep
        their nominal loads.
        """
        force = nominal.sum(dim=-1)
        flying = force <= 1e-6
        share = nominal / force[:, None].clamp(min=1e-6)
        nominal_cop = (share[..., None] * self.foot[..., :2]).sum(dim=1)
        omega = self._omega()[:, None]
        xi = self.com[:, :2] + self.vel[:, :2] / omega
        walking = gait & (self.duty.mean(dim=-1) >= 0.5) & ~flying
        moved = self.xi_ref + omega * (self.xi_ref - nominal_cop) * dt
        self.xi_ref = torch.where(walking[:, None], moved, xi)
        error = torch.where(walking[:, None], xi - self.xi_ref, torch.zeros_like(xi))
        wanted = COP_GAIN * error
        fore, side = _rotate(-self.yaw, wanted[:, 0], wanted[:, 1])
        fore = fore.clamp(-FOOT_HALF_LENGTH, FOOT_HALF_LENGTH)
        side = side.clamp(-FOOT_HALF_WIDTH, FOOT_HALF_WIDTH)
        ankle_x, ankle_y = _rotate(self.yaw, fore, side)
        ankle = torch.stack([ankle_x, ankle_y], dim=-1)
        rest = wanted - ankle
        span = self.foot[:, 1, :2] - self.foot[:, 0, :2]
        move = (rest * span).sum(dim=-1) / (span * span).sum(dim=-1).clamp(min=1e-4)
        limit = SHARE_LIMIT * 2.0 * share.amin(dim=-1)
        move = torch.where(self.contact.all(dim=-1) & walking, move.clamp(-limit, limit), 0.0)
        right = share[:, 1] + move
        tracked = torch.stack([1.0 - right, right], dim=-1) * force[:, None]
        tracked = torch.where(walking[:, None], tracked, nominal)
        return tracked, ankle * walking[:, None]

    def _landing_amplitude(self, frac: torch.Tensor) -> torch.Tensor:
        """``(n, 2)``: the peak of the half-sine a foot landing now should carry.

        With the other foot down, the nominal ``π / (4 β)``: half the weight's
        impulse over a cycle. From the air, the impulse is set by what follows
        this stance, with ``ż`` the vertical speed at landing and ``D`` the stance:

        * the other foot lands only after this one lifts -- a flight follows, of
          ``Fl``: leave at ``+Fl / 2``, ``A = π (D + Fl/2 − ż) / (2 D)``; in a
          steady run, ``ż = −Fl/2`` and this is ``π / (4 β)`` again;
        * the other foot lands at ``t`` within this stance: have stopped the fall
          by then, ``A = π (t − ż) / (D (1 − cos(π t / D)))``.
        """
        stance = (self.duty * self.period[:, None]).clamp(min=1e-3)
        nominal = math.pi / (4.0 * self.duty)
        other_air = ~self.contact.flip(1)
        other_lands = (1.0 - frac.flip(1)) * self.period[:, None]
        fall = self.vel[:, 2:3]
        flight = (other_lands - stance).clamp(min=0.0)
        takeoff = math.pi * (stance + flight / 2 - fall) / (2.0 * stance)
        caught = other_lands.clamp(min=1e-3)
        arrest = math.pi * (caught - fall) / (stance * (1.0 - torch.cos(math.pi * caught / stance)))
        from_air = torch.where(other_lands >= stance, takeoff, arrest)
        return torch.where(other_air, from_air, nominal).clamp(0.3, 3.5)

    def _begin_shift(self, mask: torch.Tensor) -> None:
        """``mask``: from standing, start carrying the DCM over the stance foot."""
        first = self.goal["first"]
        period = self.goal["period"]
        start = self.goal["duty"].clamp(min=START_DUTY)
        start = torch.minimum(start, (1.0 - self.min_swing / period)[:, None])
        omega = self._omega()
        xi = self._xi()
        stance = 1 - first
        stance_foot = self.foot[torch.arange(self.num_envs, device=self.device), stance, :2]
        side = torch.where(stance == 0, 1.0, -1.0)
        offset = self.offset
        # The stance foot "just landed" for the step the first foot is about to take.
        before = torch.where(stance == 0, 1.0 - offset, offset) * period
        after = torch.where(stance == 0, offset, 1.0 - offset) * period
        stance_duty = torch.where(stance == 0, start[:, 0], start[:, 1])
        lifting_duty = torch.where(stance == 0, start[:, 1], start[:, 0])
        step, _, _ = self._steady_offset(
            side,
            self.width,
            self.v_cmd,
            before,
            after,
            self.yaw,
            omega,
            stance_duty * period,
            lifting_duty * period,
        )
        column = mask[:, None]
        self.first = torch.where(mask, first, self.first)
        self.mode = torch.where(mask, SHIFT, self.mode)
        self.mode_time = torch.where(mask, 0.0, self.mode_time)
        self.period = torch.where(mask, period, self.period)
        self.duty = torch.where(column, start, self.duty)
        self.xi_start = torch.where(column, xi, self.xi_start)
        self.xi_end = torch.where(column, stance_foot + step, self.xi_end)

    def _begin_gait(self, mask: torch.Tensor) -> None:
        """``mask``: the first foot leaves the ground."""
        duty = self.duty
        # The first foot stands at its lift-off: it leaves the ground on this substep.
        phase = torch.where(
            self.first == 0, duty[:, 0], torch.remainder(self.offset + duty[:, 1], 1.0)
        )
        self.phase = torch.where(mask, phase, self.phase)
        column = mask[:, None]
        frac = self._frac()
        self.stance_time = torch.where(column, frac * self.period[:, None], self.stance_time)
        self.amplitude = torch.where(column, math.pi / (4.0 * duty), self.amplitude)
        self.mode = torch.where(mask, GAIT, self.mode)
        self.mode_time = torch.where(mask, 0.0, self.mode_time)
        self.blend_time = torch.where(mask, 0.0, self.blend_time)
        self.blend_from = torch.where(column, self.load, self.blend_from)
        self.v_int = torch.where(column, 0.0, self.v_int)
        self.xi_ref = torch.where(column, self.xi_end, self.xi_ref)
        vx, vy = _rotate(-self.yaw, self.vel[:, 0], self.vel[:, 1])
        self.v_avg = torch.where(column, torch.stack([vx, vy], dim=-1), self.v_avg)

    def _begin_stand(self, mask: torch.Tensor) -> None:
        """``mask``: hold the DCM where it is, over the feet."""
        held = self._held(self._xi())
        column = mask[:, None]
        self.xi_start = torch.where(column, held, self.xi_start)
        self.xi_end = torch.where(column, held, self.xi_end)
        self.mode = torch.where(mask, STAND, self.mode)
        self.mode_time = torch.where(mask, 0.0, self.mode_time)
        self.blend_time = torch.where(mask, 0.0, self.blend_time)
        self.blend_from = torch.where(column, self.load, self.blend_from)

    def _recover(self) -> None:
        """Step in place when the gait drifts off, until it is back (see the module)."""
        down = self.contact
        reach = (self.com[:, None, :2] - self.foot[..., :2]).norm(dim=-1)
        nearest = torch.where(down, reach, torch.full_like(reach, math.inf)).amin(dim=-1)
        height = self.com[:, 2]
        danger = (down.any(dim=-1) & (nearest > DANGER_REACH)) | (height < DANGER_HEIGHT[0])
        danger |= (height > DANGER_HEIGHT[1]) | (self.vel[:, :2].norm(dim=-1) > DANGER_SPEED)
        xi = self._xi()
        off_feet = xi - self._held(xi)
        danger |= (self.mode == STAND) & (off_feet.norm(dim=-1) > 0.04)
        start = danger & ~self.recovering & ~self.fallen
        self.recovering = self.recovering | start
        self.recoveries = self.recoveries + start.long()
        for key in ("forward", "lateral", "turn"):
            self.goal[key] = torch.where(start, 0.0, self.goal[key])
        self.goal["standing"] = self.goal["standing"] & ~start
        self.goal["period"] = torch.where(start, self.period.clamp(0.8, 1.4), self.goal["period"])
        self.goal["duty"] = torch.where(start[:, None], 0.7, self.goal["duty"])
        self.goal["width"] = torch.where(start, 0.4, self.goal["width"])
        self.goal["height"] = torch.where(start, 0.94, self.goal["height"])
        self.goal["duration"] = torch.where(start, RECOVERY_TIME, self.goal["duration"])
        self.segment_left = torch.where(start, RECOVERY_TIME, self.segment_left)
        # The foot on the side the DCM has gone steps out to catch it.
        heading = self._heading()
        left = torch.stack([-heading[:, 1], heading[:, 0]], dim=-1)
        towards = ((off_feet * left).sum(dim=-1) < 0).long()
        self.goal["first"] = torch.where(start, towards, self.goal["first"])
        self.shift_time = torch.where(start, QUICK_SHIFT, self.shift_time)

    def _step(self, dt: float) -> None:
        """One substep, written back into the state's own tensors."""
        static = {name: getattr(self, name) for name in _STATE}
        goal, following = dict(self.goal), dict(self.next)
        self._move(dt)
        for name, tensor in static.items():
            new = getattr(self, name)
            if new is not tensor:
                tensor.copy_(new)
            setattr(self, name, tensor)
        for store, kept in ((self.goal, goal), (self.next, following)):
            for key, tensor in kept.items():
                if store[key] is not tensor:
                    tensor.copy_(store[key])
                store[key] = tensor

    def _move(self, dt: float) -> None:
        r = self.ranges
        self._recover()

        # The schedule: a segment ends and the next begins.
        self.segment_left = self.segment_left - dt
        change = self.segment_left <= 0.0
        renew = change & ~self.fixed
        for key in GAIT_KEYS:
            self.goal[key] = torch.where(
                _expand(change, self.goal[key]), self.next[key], self.goal[key]
            )
            self.next[key] = torch.where(
                _expand(renew, self.next[key]), self.spare[key], self.next[key]
            )
        length = torch.where(self.fixed, math.inf, self.goal["duration"])
        self.segment_left = torch.where(change, length, self.segment_left)
        self.shift_time = torch.where(change, SHIFT_TIME, self.shift_time)
        self.recovering = self.recovering & ~change

        # The intent: commands follow the segment's, and wander a little.
        standing = self.goal["standing"]
        moving = ~standing
        goal_v = torch.stack([self.goal["forward"], self.goal["lateral"]], dim=-1)
        goal_v = goal_v * moving[:, None]
        goal_w = self.goal["turn"] * moving
        rate = torch.clamp(SPEED_STEP / (self.period / 2), max=RAMP)[:, None] * dt
        self.v_cmd = self.v_cmd + torch.maximum(torch.minimum(goal_v - self.v_cmd, rate), -rate)
        self.w_cmd = self.w_cmd + (goal_w - self.w_cmd).clamp(-RAMP * dt, RAMP * dt)
        live = (moving & ~self.fixed).float()
        decay = dt / NOISE_TIME
        spread = math.sqrt(2.0 * decay)
        sv, sw = r.intent_noise
        self.v_noise = (self.v_noise * (1.0 - decay) + sv * spread * self.draw_v) * live[:, None]
        self.w_noise = (self.w_noise * (1.0 - decay) + sw * spread * self.draw_w) * live
        velocity = self.v_cmd + self.v_noise + self.v_int
        self.width = self.width + (self.goal["width"] - self.width).clamp(
            -WIDTH_RATE * dt, WIDTH_RATE * dt
        )
        self.height = self.height + (self.goal["height"] - self.height).clamp(
            -HEIGHT_RATE * dt, HEIGHT_RATE * dt
        )
        self.lean_rate = (self.goal["lean"] - self.lean) / LEAN_TIME
        self.lean = self.lean + self.lean_rate * dt
        self.yaw_rate = self.yaw_rate + (self.w_cmd + self.w_noise - self.yaw_rate) * (
            dt / YAW_TIME
        )
        self.yaw = self.yaw + self.yaw_rate * dt

        # Modes.
        self.mode_time = self.mode_time + dt
        self.blend_time = self.blend_time + dt
        self._begin_shift((self.mode == STAND) & moving & ~self.fallen)
        self._begin_stand((self.mode == SHIFT) & standing)
        self._begin_gait((self.mode == SHIFT) & (self.mode_time >= self.shift_time))

        # The clock, and the feet's events.
        gait = self.mode == GAIT
        before = self._frac()
        self.phase = torch.where(gait, self.phase + dt / self.period, self.phase)
        cycle = gait & (self.phase >= 1.0)
        self.phase = torch.where(cycle, self.phase - 1.0, self.phase)
        ratio = (self.goal["period"] / self.period).clamp(1.0 / PERIOD_STEP, PERIOD_STEP)
        self.period = torch.where(cycle, self.period * ratio, self.period)
        frac = self._frac()
        stepping = gait[:, None]
        landing = stepping & ~self.contact & (frac < before)
        until_landing = (1.0 - frac) * self.period[:, None]
        lifting = stepping & self.contact & (frac >= self.duty)
        put = torch.cat([self.target, torch.zeros_like(self.target[..., :1])], dim=-1)
        self.foot = torch.where(landing[..., None], put, self.foot)
        # From a landing on, the CoP tracks the DCM the foot was placed for.
        for side in (0, 1):
            self.xi_ref = torch.where(landing[:, side, None], self.landing_xi[:, side], self.xi_ref)
        self.stance_time = torch.where(landing, 0.0, self.stance_time)
        # A foot takes its duty for the next stance when it lands -- walking steps
        # while the body is stopping -- and never one that would leave its swing
        # shorter than a swing can be at the period it has now.
        duty = self.goal["duty"]
        duty = torch.where(standing[:, None], duty.clamp(min=START_DUTY), duty)
        duty = torch.minimum(torch.maximum(duty, self.duty - DUTY_STEP), self.duty + DUTY_STEP)
        duty = torch.minimum(duty, (1.0 - self.min_swing / self.period)[:, None])
        self.duty = torch.where(landing, duty, self.duty)
        self.amplitude = torch.where(landing, self._landing_amplitude(frac), self.amplitude)
        self.liftoff = torch.where(lifting[..., None], self.foot, self.liftoff)
        self.swing_time = torch.where(lifting, 0.0, self.swing_time)
        self.clearance = torch.where(lifting, self.goal["clearance"][:, None], self.clearance)
        self.target = torch.where(lifting[..., None], self.foot[..., :2], self.target)
        self.contact = (self.contact & ~lifting) | landing
        self.swing_time = torch.where(self.contact, self.swing_time, self.swing_time + dt)
        self.stance_time = torch.where(self.contact, self.stance_time + dt, self.stance_time)
        # A body stops only with the DCM over its feet: one that stops where it cannot
        # stand falls.
        xi_now = self._xi()
        over_feet = (xi_now - self._held(xi_now)).norm(dim=-1) < 0.02
        slow = self.v_avg.norm(dim=-1) < STOP_SPEED
        stop = gait & standing & self.contact.all(dim=-1) & landing.any(dim=-1) & slow & over_feet
        self._begin_stand(stop)
        gait = self.mode == GAIT
        stepping = gait[:, None]

        # Swinging feet: aim, then a minimum-jerk path and a bump of clearance.
        swing = stepping & ~self.contact
        total = (self.swing_time + until_landing).clamp(min=1e-6)
        s = (self.swing_time / total).clamp(0.0, 1.0)
        aim = swing & (s < FREEZE)
        target, xi_landing = self._aim(frac, until_landing, velocity)
        self.landing_xi = torch.where(aim[..., None], xi_landing, self.landing_xi)
        self.target_rate = torch.where(aim[..., None], (target - self.target) / dt, 0.0)
        self.target = torch.where(aim[..., None], target, self.target)
        s_dot = 1.0 / total
        sigma = s**3 * (10.0 - 15.0 * s + 6.0 * s * s)
        sigma_dot = 30.0 * s * s * (1.0 - s) ** 2 * s_dot
        start_xy = self.liftoff[..., :2]
        path = start_xy + (self.target - start_xy) * sigma[..., None]
        path_vel = (self.target - start_xy) * sigma_dot[..., None] + self.target_rate * sigma[
            ..., None
        ]
        lift = self.clearance * 16.0 * s * s * (1.0 - s) ** 2
        lift_vel = self.clearance * 32.0 * s * (1.0 - s) * (1.0 - 2.0 * s) * s_dot
        swing_pos = torch.cat([path, lift[..., None]], dim=-1)
        swing_vel = torch.cat([path_vel, lift_vel[..., None]], dim=-1)
        self.foot = torch.where(swing[..., None], swing_pos, self.foot)
        self.foot_vel = torch.where(swing[..., None], swing_vel, torch.zeros_like(self.foot_vel))

        # Loads: a half-sine per stance, or the balance of a standing body.
        balance_load, balance_cop, kappa = self._balance()
        until_lift = torch.remainder(self.duty - frac, 1.0) * self.period[:, None]
        progress = (self.stance_time / (self.stance_time + until_lift).clamp(min=1e-6)).clamp(0, 1)
        gait_load = self.contact * self.amplitude * torch.sin(math.pi * progress)
        gait_load = gait_load * (1.0 + kappa)[:, None]
        gait_load, ankle = self._track(gait_load, gait, dt)
        load = torch.where(stepping, gait_load, balance_load)
        blend = (self.blend_time / BLEND_TIME).clamp(0.0, 1.0)[:, None]
        load = blend * load + (1.0 - blend) * self.blend_from * self.contact
        force = load.sum(dim=-1)
        weighted = (load[..., None] * self.foot[..., :2]).sum(dim=1) / force[:, None].clamp(
            min=1e-6
        )
        balance_force = balance_load.sum(-1, keepdim=True).clamp(min=1e-6)
        fore = balance_cop - (balance_load[..., None] * self.foot[..., :2]).sum(1) / balance_force
        cop = torch.where(stepping, weighted + ankle, weighted + fore * blend)

        # Newton: the legs push along themselves.
        height = self.com[:, 2].clamp(min=0.2)
        acc_xy = force[:, None] * (self.com[:, :2] - cop) / height[:, None]
        acc_xy = torch.where(force[:, None] > 1e-6, acc_xy, torch.zeros_like(acc_xy))
        acc = torch.cat([acc_xy, (force - 1.0)[:, None]], dim=-1)
        self.vel = self.vel + acc * dt
        self.com = self.com + self.vel * dt
        self.load, self.cop = load, cop

        filtering = dt / HEIGHT_FILTER
        self.z_avg = self.z_avg + (self.com[:, 2] - self.z_avg) * filtering
        self.zd_avg = self.zd_avg + (self.vel[:, 2] - self.zd_avg) * filtering
        self.z_int = (self.z_int + HEIGHT_GAIN[2] * (self.height - self.z_avg) * dt).clamp(
            -0.3, 0.3
        )
        vx, vy = _rotate(-self.yaw, self.vel[:, 0], self.vel[:, 1])
        heading = torch.stack([vx, vy], dim=-1)
        self.v_avg = (
            self.v_avg + (heading - self.v_avg) * (dt / self.period.clamp(min=1.0))[:, None]
        )
        # The integral only learns a steady gait's bias: not while the command ramps,
        # nor in the gait's first cycles, when the filtered speed still lags.
        target_v = self.v_cmd + self.v_noise
        settled = (goal_v - self.v_cmd).norm(dim=-1) < 1e-3
        settled &= gait & (self.mode_time > 2.0 * self.period)
        integral = self.v_int + INTEGRAL_GAIN * (target_v - self.v_avg) * dt
        integral = integral.clamp(-INTEGRAL_LIMIT, INTEGRAL_LIMIT)
        decayed = torch.where(gait[:, None], self.v_int, self.v_int * (1.0 - dt))
        self.v_int = torch.where(settled[:, None], integral, decayed)

        # A biped that fell all the same holds its last state: the body it leads has
        # left it, and its episode ends on the lag.
        reach = (self.com[:, None, :2] - self.foot[..., :2]).norm(dim=-1)
        nearest = torch.where(self.contact, reach, torch.full_like(reach, math.inf)).amin(dim=-1)
        fell = (self.contact.any(dim=-1) & (nearest > FALL_REACH)) | (
            self.com[:, 2] < FALL_HEIGHT[0]
        )
        fell |= (self.com[:, 2] > FALL_HEIGHT[1]) | (self.vel[:, :2].norm(dim=-1) > FALL_SPEED)
        fell |= ~torch.isfinite(self.com).all(dim=-1)
        newly = fell & ~self.fallen
        self.frozen = torch.where(newly[:, None], self.record, self.frozen)
        self.fallen = self.fallen | fell
        self.record = self._record()

    def _record(self) -> torch.Tensor:
        """``(n, 27 + 3)``: ``z*`` of the biped now, then its CoM ``x, y`` and yaw."""
        n = self.num_envs
        z = torch.zeros(n, SKILL + _EXTRA, device=self.device)

        def heading(v: torch.Tensor) -> torch.Tensor:
            x, y = _rotate(-self.yaw.view(-1, *([1] * (v.dim() - 2))), v[..., 0], v[..., 1])
            return torch.stack([x, y, v[..., 2]], dim=-1)

        z[:, _HEIGHT] = self.com[:, 2]
        z[:, _VELOCITY] = heading(self.vel)
        sin_lean, cos_lean = torch.sin(self.lean), torch.cos(self.lean)
        z[:, _GRAVITY] = torch.stack([sin_lean, torch.zeros_like(sin_lean), -cos_lean], dim=-1)
        z[:, _ANGULAR] = torch.stack(
            [-sin_lean * self.yaw_rate, self.lean_rate, cos_lean * self.yaw_rate], dim=-1
        )
        relative = self.foot - self.com[:, None, :]
        z[:, _FEET] = heading(relative).flatten(1)
        z[:, _FOOT_VELOCITY] = heading(self.foot_vel).flatten(1)
        z[:, _LOAD] = self.load
        orbit = torch.linalg.cross(relative, self.foot_vel - self.vel[:, None, :], dim=-1).sum(1)
        momentum = self.leg_orbit[:, None] * orbit
        momentum[:, 2] = momentum[:, 2] + self.yaw_inertia * self.yaw_rate
        z[:, _MOMENTUM] = heading(momentum)
        z[:, SKILL] = self.com[:, 0]
        z[:, SKILL + 1] = self.com[:, 1]
        z[:, SKILL + 2] = self.yaw
        z = torch.nan_to_num(z, nan=0.0, posinf=0.0, neginf=0.0)
        return torch.where(self.fallen[:, None], self.frozen, z)


