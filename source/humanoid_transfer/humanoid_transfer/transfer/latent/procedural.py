"""Plans no task wrote: a point-mass biped on any contact schedule.

A tracker trained by RL is an inverse model over the plans it practised
(``transfer/docs/skill_space.md`` §7.3): trained on the walk's contract
alone, the G1's tracker fell 120–240 times on the published policy's gait,
and the NAO's shuffled. Whether a new task runs on a body zero-shot is a
question of coverage -- whether its plans lie where the tracker practised --
and the only coverage that does not depend on knowing the task in advance is
the set of plans a body could physically be asked for.

This module samples that set. A plan of ``z*`` for legged locomotion is not
a free 13 x 27 array: centroidal dynamics fix it once the contact schedule,
the footholds and the start of the centre of mass are given. So the family is
generated by a reduced-order body -- a point mass carried by massless legs
that push along themselves -- whose schedule and stepping are drawn from
ranges fixed by physics (:class:`GaitRanges`):

* **Contacts.** A clock of period ``P``; each foot is in stance for its duty
  ``β`` of the cycle, the right one ``offset`` behind the left. Lift-off and
  touchdown are events and a foot's duty changes only when it lands, so no
  change of parameters makes a foot jump. Duties below one half leave the
  body in the air between stances: the same family walks and runs.
* **Loads.** Each stance carries a half-sine of vertical force. Landing on a
  foot already down, its impulse is half the body's weight over a cycle,
  ``A = π / (4 β)``; landing from the air, it is the impulse that leaves the
  ground at the speed the next flight needs, or that has stopped the fall by
  the time the other foot lands -- the same in a steady run, and what lets a
  run turn into a walk. The loads' sum is the total vertical force ``F`` and
  Newton gives the height, ``z̈ = F − 1``. Long overlapping stances make the
  walk's double hump, short ones a run's single bumps with flight between --
  one model across the walk-run transition. A slow factor on ``F`` holds the
  mean height.
* **Horizontal.** The legs push along themselves, so the centre of mass is a
  variable-height inverted pendulum about the centre of pressure,
  ``c̈ = F (c − p) / c_z`` (Caron et al., 2018).
* **Stepping and balance.** A walking foot aims where the divergent
  component of motion must be when it lands for the gait to repeat at the
  commanded velocity (Englsberger et al., 2015), for the model's own centre
  of pressure, with an integral on the speed for what the model leaves out.
  Between landings the centre of pressure tracks that periodic DCM within the
  feet -- each sole's own area, and in double support the share of the load
  -- which is what keeps slow gaits, with steps longer than the pendulum's
  time, from falling between steps. A running foot aims at the neutral point
  with a velocity gain (Raibert, 1986).
* **Standing and starting.** A standing body holds its DCM with the centre of
  pressure anywhere under its feet; to start, it first carries the DCM over
  the stance foot, so it leans before it steps, as bodies do.
* **Recovering.** Rarely (a few in a thousand segments, after compound
  changes such as a slow run turning into a slow sideways walk) the gait
  drifts off. When the centre of mass leaves its stance foot by 0.4 of a leg,
  its height or speed leaves a body's range, or a standing body's DCM leaves
  its feet, the biped changes its mind as a body would: it steps in place
  until it is back, then carries on with its schedule. The plan stays a
  trajectory of the same dynamics; only the intent changed. Should it fall
  all the same (about one episode in a hundred), its plan holds still, and
  the body it leads ends its episode on the lag.
* **What a point mass does not fix** -- the base's tilt and angular velocity,
  and the angular momentum of the legs -- comes from a lean, the turn rate and
  ``k = μ Σ (p_i − c) × (ṗ_i − ċ) + ι ψ̇ ẑ``, with ``μ`` and ``ι`` measured
  on the bodies' own walks (``transfer/scripts/calibrate_procedural.py``)
  and randomised around them.

Everything is in body units (``L``, ``T``, ``V``, ``m g``), so one family
trains every body: dynamic similarity is what makes it shared. Bodies differ
in which part of it they can execute, which their trackers learn by RL and
``transfer/scripts/evaluate_competence.py`` measures.

The biped runs ahead of the body by a plan's horizon and writes its ``z*``
into a ring buffer, so every plan is a window of one continuous trajectory --
a reference clip generated online. An episode starts from the body's own
state, held still for the length of a plan, then stands for a while.
"""

