@dataclass(frozen=True)
class GaitRanges:
    """The family of plans, in body units. Every range is set by physics, before any task.

    Speeds stay below a Froude number of 0.2, under the walk-run transition of
    legged animals (``Fr ≈ 0.5``) and above both bodies' commands. The period
    is a scale and is drawn log-uniform (Jeffreys' prior). Duties go from runs
    to near-static walks. Width, height and clearance bracket a standing
    posture; the height range spans the G1's walking height (0.95 ``L``) and
    the NAO's nominal one (1.08 ``L``) as far as a crouch allows.
    """

    forward: tuple[float, float] = (-0.10, 0.45)
    lateral: tuple[float, float] = (-0.15, 0.15)
    turn: tuple[float, float] = (-0.30, 0.30)
    period: tuple[float, float] = (0.6, 3.0)
    duty: tuple[float, float] = (0.30, 0.95)
    duty_asymmetry: float = 0.08
    """Half-width of the difference between the two feet's duties."""

    phase_jitter: float = 0.05
    """Half-width of the right foot's offset around half a cycle, per episode."""

    width: tuple[float, float] = (0.20, 0.55)
    height: tuple[float, float] = (0.85, 1.00)
    clearance: tuple[float, float] = (0.01, 0.12)
    lean: tuple[float, float] = (0.0, 0.20)
    standing: float = 0.2
    """Share of segments spent standing still."""

    segment: tuple[float, float] = (4.0, 20.0)
    first_stand: tuple[float, float] = (0.5, 2.5)
    """How long an episode stands, after its held start, before its first gait."""

    min_swing: float = 0.12
    """Shortest swing, in ``T``. A body also needs :data:`SWING_STEPS` control steps."""

    max_stride: float = 1.0
    max_step: float = 0.55
    max_swing_speed: float = 2.0
    """Mean speed of a swinging foot, ``|v| / (1 − β)``, in ``V``. Walking humans: about 1."""

    max_bounce: float = 0.08
    """How far a stance may lift and drop the centre of mass, in ``L``: ``(A − 1)(β P / π)²``
    with ``A = π / (4 β)`` the half-sine's peak. Humans: about 0.055 walking, 0.07 running;
    a slow run (long stances and long flights) would bounce a tenth of a leg."""

    leg_orbit: tuple[float, float] = (0.05, 0.30)
    """``μ``: how much of the feet's orbital momentum the body's angular momentum carries."""

    yaw_inertia: tuple[float, float] = (0.0, 0.05)
    """``ι``: the body's yaw inertia, in ``m L²``."""

    intent_noise: tuple[float, float] = (0.02, 0.03)
    """Stationary spread of the intent's wander, on velocity (``V``) and turn (``1/T``)."""


